// Package gen turns a model.File IR into Go source code.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"

	"github.com/thomas666-beast/moo/internal/model"
)

// Generate renders Go source for the given IR. The returned bytes are gofmt'd.
func Generate(f *model.File) ([]byte, error) {
	funcs := template.FuncMap{
		"exportedWritable": func(s *model.StructSpec) []*model.FieldSpec {
			return s.WritableFields()
		},
		"hasDefault": func(f *model.FieldSpec) bool {
			return !f.Skip && f.Default != ""
		},
	}

	tmpl, err := template.New("moo").Funcs(funcs).Parse(fileTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, f); err != nil {
		return nil, fmt.Errorf("execute template: %w", err)
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated source: %w\n----\n%s", err, buf.String())
	}
	return out, nil
}

const fileTemplate = `// Code generated by moo. DO NOT EDIT.

package {{.Package}}
{{range .Structs}}
{{- $s := .}}
// ---- {{$s.Name}} ----

// {{$s.Name}}Option configures a {{$s.Name}}.
type {{$s.Name}}Option func(*{{$s.Name}})
{{range exportedWritable $s}}
// With{{.Name}} sets the {{.Name}} field.
func With{{.Name}}(v {{.GoType}}) {{$s.Name}}Option {
	return func(x *{{$s.Name}}) { x.{{.Name}} = v }
}
{{end}}
// New{{$s.Name}} constructs a {{$s.Name}} with defaults applied, then options.
func New{{$s.Name}}(opts ...{{$s.Name}}Option) *{{$s.Name}} {
	x := &{{$s.Name}}{
{{- range $s.Fields}}
{{- if hasDefault .}}
		{{.Name}}: {{.Default}},
{{- end}}
{{- end}}
	}
	for _, opt := range opts {
		opt(x)
	}
	return x
}
{{end}}`
